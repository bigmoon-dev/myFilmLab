"""build_looks.py — looks.cfg → LOOKS.BIN (VBIN) + AutoRun.txt

MVP 打包器：
  1. 解析 looks.cfg（INI 格式配方）
  2. 配方表 → 二进制数据段
  3. 组装 VBIN 容器（fpSup 兼容格式：VBIN magic + count + entry + len + (addr,len) 表 + body）
  4. 生成 AutoRun.txt 骨架（机制占位：apply_mechanism 待 P2 定案后填充）

用法：python build_looks.py looks.cfg --out-dir ../dist
"""
import argparse
import configparser
import struct
import os

# ---- 常量（来自 DESIGN_PAYLOAD.md 地址表）----
CAVE_LOW   = 0xC072DE64      # stage1 引导器洞区
WORKER_AT  = 0xC072E800      # 监视任务安放地址
HOOK       = 0xC00D0794      # 陀螺回调钩子位
ECHO_SLOT  = 0xC0BAC2F8      # echo 命令劫持槽
MODE_MASTER= 0xC31F8914      # 模式主拷贝（监视目标）

MODE_ENUMS = {  # menu# -> enum（简报 18 实测）
    'STD':0x00,'VIV':0x03,'NTR':0x05,'PORT':0x06,'LAND':0x07,'CINE':0x08,
    'TO':0x0A,'SUNR':0x0B,'FORG':0x0C,'FOVB':0x0E,'FOVY':0x0F,'MONO':0x01,
    'OFF':0x24,'POWB':0x0D,'WGLD':0x09,
    'DUO_R1':0x18,'DUO_OR1':0x19,'DUO_YE1':0x1A,'DUO_YG1':0x1B,'DUO_G1':0x1C,
    'DUO_G2':0x1D,'DUO_B1':0x1E,'DUO_B2':0x1F,'DUO_P1':0x20,'DUO_M1':0x21,
    'HID02':0x02,'HID04':0x04,'HID10':0x10,
}

# ---- 配方二进制记录 ----
# struct look_rec { u8 host_enum; u8 base_enum; i8 sat, con, ton, shp, eff; u8 flags; u8 rsv; char name[12]; }  = 20 bytes
LOOK_REC = '<BBbbbbbBB12s'
LOOK_REC_SIZE = struct.calcsize(LOOK_REC)

def parse_cfg(path):
    cp = configparser.ConfigParser()
    cp.read(path, encoding='utf-8')
    looks = []
    for sec in cp.sections():
        g = cp[sec]
        host = MODE_ENUMS[g.get('host', '').strip().upper()]
        base = MODE_ENUMS[g.get('mode', 'STD').strip().upper()]
        look = dict(
            name=sec, host=host, base=base,
            sat=int(g.get('sat', 0)), con=int(g.get('con', 0)),
            ton=int(g.get('ton', 0)), shp=int(g.get('shp', 0)),
            eff=int(g.get('eff', 0)),
            display=g.get('name', sec))
        looks.append(look)
    return looks

def build_recipe_section(looks):
    out = bytearray()
    out += struct.pack('<I', len(looks))
    out += struct.pack('<I', MODE_MASTER)   # 监视目标地址
    for lk in looks:
        nm = lk['display'].encode('ascii', 'replace')[:12]
        out += struct.pack(LOOK_REC, lk['host'], lk['base'],
                           lk['sat'], lk['con'], lk['ton'], lk['shp'], lk['eff'],
                           0, 0, nm)
    return bytes(out)

# ---- VBIN 组装 ----
def build_vbin(sections, entry_offset_in_first):
    """sections: list of (addr, bytes). addr==None → staging(0)."""
    body = bytearray()
    table = []
    for addr, data in sections:
        if len(body) % 4:
            body += b'\x00' * (4 - len(body) % 4)
        table.append((addr if addr is not None else 0, len(data)))
        body += data
    hdr = struct.pack('<4sIII', b'VBIN', len(sections), entry_offset_in_first, len(body))
    tbl = b''.join(struct.pack('<II', a, l) for a, l in table)
    return hdr + tbl + bytes(body)

# ---- AutoRun 生成（骨架；apply 机制待 P2 定案）----
AUTORUN_TEMPLATE = """# LOOKS loader generated by build_looks.py — fw 5.02 only
# 机制：{mechanism}（P2 定案后此处生成完整 mem set 序列）
# 仅供参考的结构骨架：
# stage1 借道 echo：mem set {echo_slot} <loader_addr>
# echo
# mem set {echo_slot} <echo_orig>
# 装载 LOOKS.BIN → VBIN 摆放 → 钩子武装（0xC00D0794）
version
# TODO(P2): 完整序列
"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('cfg')
    ap.add_argument('--out-dir', default='../dist')
    args = ap.parse_args()
    looks = parse_cfg(args.cfg)
    print(f'parsed {len(looks)} looks:')
    for lk in looks:
        print(f"  {lk['display']:12s} host=0x{lk['host']:02X} base=0x{lk['base']:02X} "
              f"sat={lk['sat']} con={lk['con']} ton={lk['ton']} shp={lk['shp']} eff={lk['eff']}")
    recipes = build_recipe_section(looks)
    os.makedirs(args.out_dir, exist_ok=True)
    # MVP 段布局：stage1 占位 + 配方数据 + 钩子（入口与 stage1 待汇编部分接入）
    vbin = build_vbin([(None, recipes)], entry_offset_in_first=0)
    open(os.path.join(args.out_dir, 'LOOKS.BIN'), 'wb').write(vbin)
    open(os.path.join(args.out_dir, 'AutoRun.txt'), 'w').write(
        AUTORUN_TEMPLATE.format(mechanism='TBD', echo_slot=f'0x{ECHO_SLOT:08X}'))
    print(f"LOOKS.BIN ({len(vbin)} B) + AutoRun.txt -> {args.out_dir}")
    print("NOTE: stage1/monitor 汇编体与 apply 机制接入是 P2/P3 后的下一步")

if __name__ == '__main__':
    main()
